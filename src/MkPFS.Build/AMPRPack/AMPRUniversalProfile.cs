using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using MkPFS.Core.Util;

namespace MkPFS.Build.AMPRPack;

/// <summary>
/// The pack profile the PS5 LZ4 Game Compressor builds from a game's folder structure, without traces or a TOML file
/// (port of <c>ampr-native/src/universal_profile.h</c> and <c>safety_patterns.h</c>). Files in subfolders, numbered
/// root files and known asset types are packed with LZ4; audio folders get small hot blocks; video, audio streams,
/// executables, system data and already encoded media stay loose. Rules are last-match-wins, so the safety rule
/// always has the final say.
/// </summary>
public static partial class AMPRUniversalProfile
{
    /// <summary>The compressor's default level.</summary>
    public const int DefaultLevel = 7;

    /// <summary>Levels up to this one use the LZ4 fast encoder; higher ones use LZ4 HC at that level.</summary>
    public const int FastLevelLimit = 4;

    /// <summary>First line of every generated profile.</summary>
    public const string Header = "# Universal profile generated by scanning game structure";

    private static readonly string[] AudioWords = ["sound", "audio", "sfx", "music", "voice", "vo", "dialog", "dialogue", "soundbank", "wem"];
    private static readonly string[] AudioFolders = ["sound", "audio", "sfx", "music", "voice", "vo", "dialog", "dialogue"];
    private static readonly string[] VideoWords = ["video", "movie", "movies", "cutscene", "cutscenes", "fmv", "cinematic", "cinematics"];
    private static readonly string[] StreamNames = ["movie", "movies", "soundbank", "screenreaderwem", "wem"];

    private static readonly HashSet<string> AssetTypes = new(StringComparer.Ordinal)
    {
        ".dds", ".ktx", ".ktx2", ".astc", ".basis", ".tga", ".gnf", ".gnfp", ".jxm", ".vtf", ".dat", ".res", ".uasset", ".ubulk", ".bin",
    };

    /// <summary>
    /// Functional exclusions (<c>safety_patterns.h</c>): loaders, system data and already encoded media stay loose.
    /// <c>fakelib2</c> is added to the compressor's list because ShadowMountPlus mounts it instead of <c>fakelib</c>.
    /// </summary>
    public static IReadOnlyList<string> SafetyPatterns { get; } = BuildSafetyPatterns();

    /// <summary>The rules for a game folder.</summary>
    /// <param name="relativeFiles">Every file of the game, relative to <c>/app0</c> with <c>/</c> separators.</param>
    /// <param name="level">1..12; up to <see cref="FastLevelLimit"/> selects the fast encoder.</param>
    /// <returns>TOML profile text.</returns>
    /// <exception cref="ArgumentOutOfRangeException"><paramref name="level"/> is outside 1..12.</exception>
    public static string RenderToml(IEnumerable<string> relativeFiles, int level)
    {
        ArgumentNullException.ThrowIfNull(relativeFiles);
        ArgumentOutOfRangeException.ThrowIfLessThan(level, 1);
        ArgumentOutOfRangeException.ThrowIfGreaterThan(level, 12);

        // 1. Classify the tree: nested files, numbered root files, top-level audio/video folders, extensions.
        SortedSet<string> suffixes = new(PythonCodePointComparer.Instance);
        List<string> numbered = [];
        bool nested = false;
        bool audio = false;
        bool video = false;
        foreach (string relative in relativeFiles)
        {
            int slash = relative.IndexOf('/', StringComparison.Ordinal);
            if (slash >= 0)
            {
                nested = true;
                string top = AsciiLower(relative[..slash]);
                audio |= AudioWords.Any(word => top.Contains(word, StringComparison.Ordinal));
                video |= VideoWords.Any(word => top.Contains(word, StringComparison.Ordinal));
            }
            else if (NumberedName().IsMatch(relative))
            {
                numbered.Add(relative);
            }

            suffixes.Add(AsciiLower(Extension(relative)));
        }

        // 2. Rules, in the compressor's order; the last matching rule wins.
        StringBuilder text = new();
        text.Append(Header).Append('\n');
        text.Append("\n[pack]\n");
        Key(text, "index_name", Str(AMPRPackConfig.DefaultIndexName));
        Key(text, "pack_pattern", Str("ampr_assets-{group}-lane{lane:02d}-vol{volume:02d}-{id:03d}.pak"));
        Key(text, "default_action", Str("loose"));
        Key(text, "default_block_size", Str("64KiB"));
        Key(text, "io_page_size", Str("64KiB"));
        Key(text, "payload_alignment", Str("64KiB"));
        Key(text, "chunk_alignment", Str("64B"));
        Key(text, "compression_mode", Str(level <= FastLevelLimit ? "fast" : "hc"));
        Key(text, "compression_level", Int(level));
        Key(text, "acceleration", "1");
        Key(text, "deduplicate", "true");
        Key(text, "deduplicate_scope", Str("lane"));
        Key(text, "deduplicate_streaming", "false");
        Key(text, "min_savings_bytes", "64");
        Key(text, "min_savings_ratio", "0.01");
        Key(text, "io_neutral_min_savings_bytes", Str("8KiB"));
        Key(text, "io_neutral_min_savings_ratio", "0.125");
        Key(text, "auto_loose_large_files", "true");
        Key(text, "auto_loose_hot_files", "false");
        Key(text, "auto_loose_min_file_size", Str("64MiB"));
        Key(text, "auto_loose_sample_blocks", "32");
        Key(text, "auto_loose_sample_bytes", Str("16MiB"));
        Key(text, "auto_loose_min_savings_ratio", "0.05");
        Key(text, "auto_loose_max_raw_ratio", "0.9");
        Key(text, "preserve_mtime", "true");
        Key(text, "validate_index_metadata", "true");

        text.Append("\n[runtime]\n");
        Key(text, "decoded_cache_bytes", Str("256MiB"));
        Key(text, "physical_cache_bytes", Str("64MiB"));
        Key(text, "workers", "8");
        Key(text, "latency_reserve_workers", "1");

        text.Append("\n[groups.assets]\n");
        Key(text, "pack_count", "4");
        Key(text, "assignment", Str("balanced"));
        Key(text, "max_pack_size", Str("16GiB"));
        Key(text, "stripe_large_files", "false");

        if (nested)
        {
            MixedRule(text, ["*/**"]);
        }

        if (numbered.Count > 0)
        {
            numbered.Sort(PythonCodePointComparer.Instance);
            MixedRule(text, numbered);
        }

        List<string> assets = [.. suffixes.Where(AssetTypes.Contains).Select(suffix => "**/*" + suffix)];
        if (assets.Count > 0)
        {
            MixedRule(text, assets);
        }

        if (audio)
        {
            HotRule(text, [.. AudioFolders.Select(name => $"**/{name}/**")]);
        }

        if (video)
        {
            LooseRule(text, [.. VideoWords.Select(name => $"**/{name}/**")]);
        }

        List<string> streams = [];
        foreach (string name in StreamNames)
        {
            streams.Add("**/" + name);
            if (name != "screenreaderwem")
            {
                streams.Add($"**/{name}_*");
            }

            if (name is "screenreaderwem" or "wem")
            {
                streams.Add($"**/{name}.*");
            }
        }

        LooseRule(text, streams);
        if (suffixes.Any(suffix => suffix.Contains("soundbank", StringComparison.Ordinal)))
        {
            HotRule(text, ["**/soundbank.*"]);
        }

        LooseRule(text, SafetyPatterns);
        return text.ToString();
    }

    /// <summary>Parse a profile from <see cref="RenderToml"/>.</summary>
    /// <param name="toml">Profile text.</param>
    /// <returns>Configuration.</returns>
    public static AMPRPackConfig ToConfig(string toml) =>
        AMPRPackConfig.FromTable(AMPRToml.Parse(toml, "universal profile"), Directory.GetCurrentDirectory());

    private static List<string> BuildSafetyPatterns()
    {
        List<string> patterns = [];
        void Both(string name)
        {
            patterns.Add(name);
            patterns.Add("**/" + name);
        }

        Both("eboot.bin");
        foreach (string category in (string[])[
                     "elf self prx sprx bak dat utoc",
                     "json ini cfg xml txt",
                     "bk2 mp4 ivf usm bnk wem at9 pfs img",
                     "png jpg jpeg webp gif bmp ico tga tif tiff exr hdr psd",
                     "dds ktx ktx2 astc basis gnf gnfp jxm vtf",
                     "zip 7z rar gz xz bz2 zst lz4",
                     "mp3 ogg flac aac opus m4a avi mkv mov wmv flv webm m4v"])
        {
            foreach (string extension in category.Split(' '))
            {
                Both("*." + extension);
            }
        }

        foreach (string directory in (string[])["decrypted", "sce_module", "sce_sys", "system", "mods", "save", "fakelib", "fakelib2", "_DUPLEX_", "trophy2", "uds"])
        {
            Both(directory + "/**");
        }

        foreach (string file in (string[])["ampr_emu.index", "ampr_assets.index", "ampr_assets.index.crc", "ampr_assets.index.runtime"])
        {
            Both(file);
        }

        patterns.Add("ampr_assets-*.pak");
        patterns.Add("**/*.pak");
        return patterns;
    }

    private static void MixedRule(StringBuilder text, IReadOnlyList<string> include)
    {
        text.Append("\n[[rule]]\n");
        Key(text, "action", Str("compress"));
        Key(text, "group", Str("assets"));
        Key(text, "layout", Str("mixed"));
        Key(text, "block_size", Str("64KiB"));
        Key(text, "include", List(include));
    }

    private static void HotRule(StringBuilder text, IReadOnlyList<string> include)
    {
        text.Append("\n[[rule]]\n");
        Key(text, "action", Str("compress"));
        Key(text, "group", Str("assets"));
        Key(text, "layout", Str("random"));
        Key(text, "block_size", Str("16KiB"));
        Key(text, "hot", "true");
        Key(text, "min_savings_bytes", "16");
        Key(text, "min_savings_ratio", "0.0025");
        Key(text, "io_neutral_min_savings_bytes", Str("2KiB"));
        Key(text, "io_neutral_min_savings_ratio", "0.125");
        Key(text, "include", List(include));
    }

    private static void LooseRule(StringBuilder text, IReadOnlyList<string> include)
    {
        text.Append("\n[[rule]]\n");
        Key(text, "action", Str("loose"));
        Key(text, "include", List(include));
    }

    private static void Key(StringBuilder text, string key, string value) => text.Append(key).Append(" = ").Append(value).Append('\n');

    private static string Int(int value) => value.ToString(CultureInfo.InvariantCulture);

    private static string List(IReadOnlyList<string> values) => "[" + string.Join(", ", values.Select(Str)) + "]";

    // TOML basic string: quotes, backslashes and control characters (DEL included) escaped.
    private static string Str(string value)
    {
        StringBuilder text = new(value.Length + 2);
        text.Append('"');
        foreach (char c in value)
        {
            switch (c)
            {
                case '"':
                    text.Append("\\\"");
                    break;
                case '\\':
                    text.Append("\\\\");
                    break;
                case < ' ' or '\u007f':
                    text.Append(CultureInfo.InvariantCulture, $"\\u{(int)c:X4}");
                    break;
                default:
                    text.Append(c);
                    break;
            }
        }

        return text.Append('"').ToString();
    }

    // std::tolower in the C locale: ASCII letters only.
    private static string AsciiLower(string value) =>
        string.Create(value.Length, value, static (span, source) =>
        {
            for (int i = 0; i < source.Length; i++)
            {
                char c = source[i];
                span[i] = c is >= 'A' and <= 'Z' ? (char)(c + 0x20) : c;
            }
        });

    // std::filesystem::path::extension: from the last dot of the file name, except a leading dot (".hidden" has none).
    private static string Extension(string relative)
    {
        string name = relative[(relative.LastIndexOf('/') + 1)..];
        int dot = name.LastIndexOf('.');
        return dot <= 0 || name is ".." ? string.Empty : name[dot..];
    }

    // Root files such as "data.001" or "chunk12.pak" (std::regex_match: the whole name).
    [GeneratedRegex(@"^(?:[a-zA-Z_]+\.[0-9]+|[a-zA-Z_]+[0-9]+\.[a-zA-Z]+)\z", RegexOptions.CultureInvariant)]
    private static partial Regex NumberedName();
}
